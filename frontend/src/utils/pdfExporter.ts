
import { jsPDF } from 'jspdf'
import autoTable from 'jspdf-autotable'
import type { RepositoryAnalysis } from '../types/repository'

type PDFDocument = jsPDF & {
  lastAutoTable?: {
    finalY: number
  }
}

const PAGE_WIDTH = 210
const PAGE_HEIGHT = 297
const LEFT = 15
const RIGHT = 195
const CONTENT_WIDTH = RIGHT - LEFT

const COLORS = {
  dark: [15, 23, 42] as [number, number, number],
  violet: [109, 40, 217] as [number, number, number],
  light: [245, 243, 255] as [number, number, number],
  text: [51, 65, 85] as [number, number, number],
  muted: [100, 116, 139] as [number, number, number],
}

function addPageHeader(doc: jsPDF, title: string) {
  doc.setFillColor(...COLORS.dark)
  doc.rect(0, 0, PAGE_WIDTH, 18, 'F')

  doc.setTextColor(255, 255, 255)
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(9)
  doc.text('CODEATLAS', LEFT, 11)

  doc.setFont('helvetica', 'normal')
  doc.setFontSize(8)
  doc.text(title, RIGHT, 11, { align: 'right' })

  doc.setTextColor(...COLORS.text)
}

function addFooter(doc: jsPDF) {
  const pageCount = doc.getNumberOfPages()

  for (let page = 1; page <= pageCount; page += 1) {
    doc.setPage(page)

    doc.setDrawColor(226, 232, 240)
    doc.line(LEFT, 284, RIGHT, 284)

    doc.setFont('helvetica', 'normal')
    doc.setFontSize(8)
    doc.setTextColor(...COLORS.muted)

    doc.text('Generated by CodeAtlas', LEFT, 290)
    doc.text(`Page ${page} of ${pageCount}`, RIGHT, 290, {
      align: 'right',
    })
  }
}

function addSectionTitle(doc: jsPDF, title: string, y: number) {
  if (y > 250) {
    doc.addPage()
    addPageHeader(doc, 'Repository Intelligence Report')
    y = 30
  }

  doc.setFont('helvetica', 'bold')
  doc.setFontSize(13)
  doc.setTextColor(...COLORS.violet)
  doc.text(title, LEFT, y)

  doc.setDrawColor(221, 214, 254)
  doc.line(LEFT, y + 3, RIGHT, y + 3)

  return y + 11
}

function addParagraph(
  doc: jsPDF,
  content: string,
  y: number,
  fontSize = 9
) {
  const safeContent = content || 'Not available'
  const lines = doc.splitTextToSize(safeContent, CONTENT_WIDTH)

  doc.setFont('helvetica', 'normal')
  doc.setFontSize(fontSize)
  doc.setTextColor(...COLORS.text)

  let currentY = y

  for (const line of lines) {
    if (currentY > 274) {
      doc.addPage()
      addPageHeader(doc, 'Repository Intelligence Report')
      currentY = 30
    }

    doc.text(line, LEFT, currentY)
    currentY += fontSize * 0.48
  }

  return currentY + 5
}

function addTable(
  doc: jsPDF,
  head: string[],
  body: string[][],
  startY: number,
  columnWidths?: number[]
) {
  autoTable(doc, {
    startY,
    head: [head],
    body: body.length
      ? body
      : [head.map((_, index) => (index === 0 ? 'No data available' : ''))],
    theme: 'grid',
    margin: {
      left: LEFT,
      right: PAGE_WIDTH - RIGHT,
      bottom: 20,
      top: 25,
    },
    showHead: 'everyPage',
    rowPageBreak: 'avoid',
    styles: {
      font: 'helvetica',
      fontSize: 8,
      cellPadding: 3,
      overflow: 'linebreak',
      textColor: COLORS.text,
      lineColor: [226, 232, 240],
      lineWidth: 0.15,
    },
    headStyles: {
      fillColor: COLORS.dark,
      textColor: [255, 255, 255],
      fontStyle: 'bold',
    },
    alternateRowStyles: {
      fillColor: [248, 250, 252],
    },
    columnStyles: columnWidths
      ? Object.fromEntries(
          columnWidths.map((width, index) => [
            index,
            { cellWidth: width },
          ])
        )
      : {},
  })

  const finalY =
    (doc as PDFDocument).lastAutoTable?.finalY ?? startY + 10

  return finalY + 9
}

function addNewSectionPage(doc: jsPDF, title: string) {
  doc.addPage()
  addPageHeader(doc, title)
  return 30
}

export function exportRepositoryPDF(analysis: RepositoryAnalysis) {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  }) as PDFDocument

  const repo = analysis.repository
  const dependencies = analysis.dependencies
  const explanation = analysis.repository_explanation

  const generatedAt = new Date().toLocaleString()

  // --------------------------------------------------
  // COVER PAGE
  // --------------------------------------------------

  doc.setFillColor(...COLORS.dark)
  doc.rect(0, 0, PAGE_WIDTH, PAGE_HEIGHT, 'F')

  doc.setFillColor(...COLORS.violet)
  doc.circle(170, 55, 35, 'F')

  doc.setTextColor(196, 181, 253)
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(12)
  doc.text('CODEATLAS', LEFT, 55)

  doc.setTextColor(255, 255, 255)
  doc.setFontSize(29)
  doc.text('Repository', LEFT, 105)
  doc.text('Intelligence', LEFT, 119)
  doc.text('Report', LEFT, 133)

  doc.setDrawColor(167, 139, 250)
  doc.setLineWidth(1)
  doc.line(LEFT, 146, 85, 146)

  doc.setFont('helvetica', 'bold')
  doc.setFontSize(15)
  doc.text(repo.full_name, LEFT, 165)

  doc.setFont('helvetica', 'normal')
  doc.setFontSize(10)

  const description = doc.splitTextToSize(
    repo.description || 'No repository description provided.',
    165
  )

  doc.text(description, LEFT, 177, {
    maxWidth: 165,
  })

  doc.setTextColor(196, 181, 253)
  doc.setFontSize(9)
  doc.text('REPOSITORY OVERVIEW', LEFT, 215)

  doc.setTextColor(255, 255, 255)
  doc.setFontSize(11)

  const coverStats = [
    `Stars: ${repo.stars.toLocaleString()}`,
    `Forks: ${repo.forks.toLocaleString()}`,
    `Files: ${analysis.statistics.total_files}`,
    `Primary language: ${Object.entries(analysis.languages).sort((a, b) => b[1] - a[1])[0]?.[0] || 'Unknown'}`,
  ]

  coverStats.forEach((stat, index) => {
    doc.text(stat, LEFT, 229 + index * 9)
  })

  doc.setTextColor(203, 213, 225)
  doc.setFontSize(8)
  doc.text(`Generated: ${generatedAt}`, LEFT, 270)
  doc.text('Static repository analysis • No repository code executed', LEFT, 279)

  // --------------------------------------------------
  // PAGE 2: REPOSITORY OVERVIEW
  // --------------------------------------------------

  let y = addNewSectionPage(doc, 'Repository Overview')

  y = addSectionTitle(doc, 'Repository Information', y)

  y = addTable(
    doc,
    ['Property', 'Value'],
    [
      ['Repository', repo.full_name],
      ['Description', repo.description || 'Not provided'],
      ['Default branch', repo.default_branch],
      ['Repository URL', repo.url],
      ['Repository size', `${repo.size_kb.toLocaleString()} KB`],
      ['Stars', repo.stars.toLocaleString()],
      ['Forks', repo.forks.toLocaleString()],
    ],
    y,
    [45, 135]
  )

  y = addSectionTitle(doc, 'Repository Statistics', y)

  y = addTable(
    doc,
    ['Metric', 'Value'],
    [
      ['Total files', String(analysis.statistics.total_files)],
      ['Total directories', String(analysis.statistics.total_directories)],
      ['Analyzed source files', String(dependencies.summary.analyzed_files)],
      ['Dependency relationships', String(dependencies.summary.dependency_count)],
      ['Entry point candidates', String(dependencies.summary.entry_point_count)],
      ['Circular dependency groups', String(dependencies.summary.circular_dependency_groups)],
      ['Detected modules', String(dependencies.summary.module_count)],
      ['File tree truncated', analysis.statistics.tree_truncated ? 'Yes' : 'No'],
    ],
    y,
    [85, 95]
  )

  // --------------------------------------------------
  // LANGUAGE DISTRIBUTION
  // --------------------------------------------------

  y = addSectionTitle(doc, 'Programming Language Distribution', y)

  const languageRows = Object.entries(analysis.languages)
    .sort((a, b) => b[1] - a[1])
    .map(([language, bytes]) => [
      language,
      `${bytes.toLocaleString()} bytes`,
    ])

  addTable(
    doc,
    ['Language', 'Code size'],
    languageRows,
    y,
    [85, 95]
  )

  // --------------------------------------------------
  // TECHNOLOGY STACK
  // --------------------------------------------------

  if (explanation) {
    addNewSectionPage(doc, 'Technology Stack')
    y = addSectionTitle(doc, 'Detected Technologies', 30)

    y = addTable(
      doc,
      ['Technology', 'Category', 'Description'],
      explanation.technology_stack.map((item) => [
        item.name,
        item.category,
        item.description,
      ]),
      y,
      [38, 35, 107]
    )

    addParagraph(
      doc,
      'Technology information is derived from repository files and manifests detected by the analysis engine.',
      y
    )
  }

  // --------------------------------------------------
  // DEPENDENCY ANALYSIS
  // --------------------------------------------------

  y = addNewSectionPage(doc, 'Dependency Intelligence')
  y = addSectionTitle(doc, 'Dependency Analysis Summary', y)

  y = addTable(
    doc,
    ['Metric', 'Value'],
    [
      ['Analyzed files', String(dependencies.summary.analyzed_files)],
      ['Dependency relationships', String(dependencies.summary.dependency_count)],
      ['Entry points', String(dependencies.summary.entry_point_count)],
      ['Circular dependency groups', String(dependencies.summary.circular_dependency_groups)],
      ['Modules', String(dependencies.summary.module_count)],
    ],
    y,
    [90, 90]
  )

  y = addSectionTitle(doc, 'Entry Points', y)

  y = addTable(
    doc,
    ['Detected entry point'],
    dependencies.entry_points.map((path) => [path]),
    y
  )

  y = addSectionTitle(doc, 'Circular Dependencies', y)

  const cycleRows = dependencies.cycles.flatMap((cycle, index) =>
    cycle.map((file, fileIndex) => [
      fileIndex === 0 ? `Cycle ${index + 1}` : '',
      `${fileIndex + 1}. ${file}`,
    ])
  )

  addTable(
    doc,
    ['Group', 'Files involved'],
    cycleRows,
    y,
    [28, 152]
  )

  // --------------------------------------------------
  // ARCHITECTURE INSIGHTS
  // --------------------------------------------------

  if (dependencies.architecture) {
    const architecture = dependencies.architecture

    y = addNewSectionPage(doc, 'Architecture Insights')
    y = addSectionTitle(doc, 'Architecture Assessment', y)

    y = addParagraph(
      doc,
      `Architecture score: ${architecture.score}/100 — ${architecture.label}`,
      y
    )

    y = addParagraph(
      doc,
      architecture.score_explanation,
      y
    )

    const metrics = architecture.metrics

    y = addTable(
      doc,
      ['Architecture metric', 'Value'],
      [
        ['Total files', String(metrics.total_files)],
        ['Total dependencies', String(metrics.total_dependencies)],
        ['Isolated files', String(metrics.isolated_files)],
        ['Circular dependency groups', String(metrics.circular_dependency_groups)],
        ['Entry point candidates', String(metrics.entry_point_candidates)],
        ['Modules', String(metrics.modules)],
        ['Graph density', String(metrics.graph_density)],
      ],
      y,
      [100, 80]
    )

    y = addSectionTitle(doc, 'Highly Connected Files', y)

    y = addTable(
      doc,
      ['File', 'Dependencies', 'Dependents', 'Connections'],
      architecture.highly_connected_files.map((file) => [
        file.path,
        String(file.dependencies),
        String(file.dependents),
        String(file.connections),
      ]),
      y,
      [90, 30, 30, 30]
    )

    y = addSectionTitle(doc, 'Isolated Files', y)

    addTable(
      doc,
      ['File path'],
      architecture.isolated_file_paths.map((path) => [path]),
      y
    )
  }

  // --------------------------------------------------
  // MODULE EXPLANATIONS
  // --------------------------------------------------

  if (explanation) {
    addNewSectionPage(doc, 'Module Explorer')
    y = addSectionTitle(doc, 'Repository Modules', 30)

    for (const module of explanation.modules) {
      y = addParagraph(
        doc,
        `${module.name} (${module.file_count} files)`,
        y,
        10
      )

      y = addParagraph(doc, module.description, y)

      y = addTable(
        doc,
        ['Files'],
        module.files.map((file) => [file]),
        y
      )
    }
  } else {
    y = addNewSectionPage(doc, 'Module Explorer')
    y = addSectionTitle(doc, 'Detected Dependency Modules', y)

    addTable(
      doc,
      ['Module', 'File count', 'Files'],
      dependencies.modules.map((module) => [
        module.name,
        String(module.file_count),
        module.files.join(', '),
      ]),
      y,
      [40, 25, 115]
    )
  }

  // --------------------------------------------------
  // IMPORTANT FILES
  // --------------------------------------------------

  y = addNewSectionPage(doc, 'Important Files')

  if (explanation) {
    y = addSectionTitle(doc, 'Important File Explanations', y)

    addTable(
      doc,
      ['File path', 'Purpose'],
      explanation.important_files.map((file) => [
        file.path,
        file.description,
      ]),
      y,
      [75, 105]
    )
  } else {
    y = addSectionTitle(doc, 'Important Files', y)

    addTable(
      doc,
      ['File path'],
      analysis.important_files.map((file) => [file]),
      y
    )
  }

  // --------------------------------------------------
  // DEVELOPER READING ROADMAP
  // --------------------------------------------------

  if (explanation) {
    y = addNewSectionPage(doc, 'Developer Reading Roadmap')
    y = addSectionTitle(doc, 'Recommended Reading Order', y)

    y = addTable(
      doc,
      ['Step', 'File', 'Reason'],
      explanation.reading_order.map((item, index) => [
        String(index + 1),
        item.path,
        item.reason,
      ]),
      y,
      [15, 65, 100]
    )

    y = addSectionTitle(doc, 'Execution Flow', y)

    y = addParagraph(
      doc,
      explanation.execution_flow.description,
      y
    )

    addTable(
      doc,
      ['Step', 'File', 'Description'],
      explanation.execution_flow.steps.map((step, index) => [
        String(index + 1),
        step.file,
        step.description,
      ]),
      y,
      [15, 60, 105]
    )
  }

  // --------------------------------------------------
  // ANALYSIS METHODOLOGY AND LIMITATIONS
  // --------------------------------------------------

  if (explanation) {
    y = addNewSectionPage(doc, 'Methodology & Limitations')
    y = addSectionTitle(doc, 'Analysis Evidence', y)

    y = addTable(
      doc,
      ['Evidence', 'Value'],
      [
        ['README available', explanation.evidence.readme_available ? 'Yes' : 'No'],
        ['Manifest files', explanation.evidence.manifest_files_available.join(', ') || 'None detected'],
        ['Dependency files analyzed', String(explanation.evidence.dependency_files_analyzed)],
        ['Detected dependency relationships', String(explanation.evidence.detected_dependency_relationships)],
        ['Analysis method', explanation.evidence.analysis_method],
      ],
      y,
      [75, 105]
    )

    y = addSectionTitle(doc, 'Analysis Limitations', y)

    addTable(
      doc,
      ['Limitation'],
      explanation.limitations.map((item) => [item]),
      y
    )
  }

  // --------------------------------------------------
  // ADAPTIVE ANALYSIS INFORMATION
  // --------------------------------------------------

  if (dependencies.analysis_info) {
    const info = dependencies.analysis_info

    y = addNewSectionPage(doc, 'Analysis Coverage')
    y = addSectionTitle(doc, 'Source Analysis Coverage', y)

    addTable(
      doc,
      ['Metric', 'Value'],
      [
        ['Analysis strategy', info.strategy],
        ['Source files discovered', String(info.source_files_discovered)],
        ['Source files selected', String(info.source_files_selected)],
        ['Source files fetched', String(info.source_files_fetched)],
        ['Source files analyzed', String(info.source_files_analyzed)],
        ['Source files failed', String(info.source_files_failed)],
        ['Source files skipped', String(info.source_files_skipped)],
        ['Maximum source files', String(info.max_source_files)],
        ['Maximum file size', `${info.max_file_size_bytes.toLocaleString()} bytes`],
        ['Coverage', `${info.coverage_percentage}%`],
        ['Supported languages', info.supported_languages.join(', ')],
      ],
      y,
      [90, 90]
    )
  }

  // --------------------------------------------------
  // FINAL FOOTERS AND DOWNLOAD
  // --------------------------------------------------

  addFooter(doc)

  const filename = `${repo.name.replace(/[^a-z0-9-_]/gi, '_')}-codeatlas-report.pdf`

  doc.save(filename)
}
